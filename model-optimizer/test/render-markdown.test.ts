test("plan markdown has every id and the savings sentence", () => {
  const md = renderPlanMarkdown(plan);
  for (const r of plan.routes) assert.ok(md.includes(r.id));
  assert.ok(md.includes(`a saving of`));
  assert.ok(md.includes(`${plan.metrics.savings.pct.toFixed(1)}%`));
  assert.ok(md.includes("Generated by model-optimizer"));
});

test("table rows keep a consistent column count with pipes in titles", () => {
  const p2 = structuredClone(plan);
  p2.routes[0]!.title = "Parse a|b input";
  const md = renderPlanMarkdown(p2);
  const lines = md.split("\n");
  const end = lines.indexOf("## Why each model");
  const rows = lines.slice(0, end).filter((l) => l.startsWith("| "));
  const cols = (l: string) => l.replace(/\\\|/g, "").split("|").length;
  assert.ok(rows.length > 2);
  for (const r of rows) assert.equal(cols(r), cols(rows[0]!), r);
  assert.ok(md.includes("Parse a\\|b input"));
});

test("dispatch has waves in order and each subsection once with its alias", () => {
  const d = renderDispatch(plan);
  const waves = plan.metrics.schedule.waves;
  let pos = -1;
  waves.forEach((_, i) => {
    const at = d.indexOf(`## Wave ${i + 1}\n`);
    assert.ok(at > pos);
    pos = at;
  });
  assert.equal((d.match(/^## Wave \d+$/gm) ?? []).length, waves.length);
  for (const r of plan.routes) {
    const heads = d.split("\n").filter((l) => l.startsWith(`### ${r.id} - `));
    assert.equal(heads.length, 1);
    const block = d.slice(d.indexOf(heads[0]!));
    assert.ok(block.slice(0, block.indexOf("Prompt:")).includes(`model: ${r.agent_alias}`));
  }
});

test("dispatch prompts equal buildTaskPrompt output", () => {
  const d = renderDispatch(plan);
  for (const sub of plan.decomposition.subsections) {
    const route = plan.routes.find((r) => r.id === sub.id)!;
    const upstream = sub.inputs.filter((i) => i.from !== "project").map((i) => ({ artifact: i.artifact, from: i.from }));
    const prompt = buildTaskPrompt({ decomposition: plan.decomposition, sub, route, upstream, mode: "agent" });
    assert.ok(d.includes(`\`\`\`\`\n${prompt}\n\`\`\`\``));
  }
});

test("mopt log lines use assigned alias and effort", () => {
  const d = renderDispatch(plan, { planPath: "my-plan.json" });
  for (const r of plan.routes) {
    assert.ok(d.includes(`mopt log --plan my-plan.json --id ${r.id} --model ${r.agent_alias} --effort ${r.effort} --result pass`));
  }
});

test("run markdown shows escalated attempts", () => {
  const md = renderRunMarkdown(summary, plan);
  assert.ok(md.includes("missing-criterion-xyz"));
  assert.ok(md.includes("needs-more-detail"));
  assert.ok(md.includes("Attempt 2"));
  assert.ok(md.includes(".mopt/run-1"));
});

test("rendering is deterministic", () => {
  assert.equal(renderPlanMarkdown(plan), renderPlanMarkdown(plan));
  assert.equal(renderDispatch(plan), renderDispatch(plan));
  assert.equal(renderRunMarkdown(summary, plan), renderRunMarkdown(summary, plan));
});
