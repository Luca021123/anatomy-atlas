// Generates docs/REFERENCES.md: every clinician calculator with its summary and references,
// read directly from the calculator definition files so the document never drifts from the code.
// Usage: node tools/refs.cjs
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.resolve(__dirname, '..');
const LIB = path.join(ROOT, 'clinician/lib');

const files = fs.readdirSync(LIB).filter(f => /^calcs-.*\.js$/.test(f));
const defs = [];
for (const f of files) {
  delete require.cache[require.resolve(path.join(LIB, f))];
  const mod = require(path.join(LIB, f));
  (Array.isArray(mod) ? mod : []).forEach(d => defs.push(Object.assign({ file: 'clinician/lib/' + f }, d)));
}
defs.sort((a, b) => String(a.category).localeCompare(String(b.category)) || String(a.name).localeCompare(String(b.name)));

const lines = [
  '# Calculator references',
  '',
  `This file is generated by \`node tools/refs.cjs\` from the calculator definitions in \`clinician/lib/\`, so it always matches the code. It lists ${defs.length} calculators. Each one cites the original publication and, where relevant, the guideline that defines its interpretation. Open any calculator in the app and expand "How it is calculated" to see its formula.`,
  ''
];
let cat = null;
for (const d of defs) {
  if (d.category !== cat) { cat = d.category; lines.push(`## ${cat || 'Other'}`, ''); }
  lines.push(`### ${d.name}`, '', `${d.summary || ''} (\`#/calculators/${d.id}\`)`, '');
  (d.references || []).forEach((r, i) => lines.push(`${i + 1}. ${r.url ? `[${r.label}](${r.url})` : r.label}`));
  lines.push('');
}
fs.writeFileSync(path.join(ROOT, 'docs/REFERENCES.md'), lines.join('\n'));
console.log(`docs/REFERENCES.md written (${defs.length} calculators from ${files.length} files)`);
