/** Markdown renderers: a shareable plan report and a finished-run report. */
import type { Config, Issue, RoutedPlan, RunSummary, Routing, SubsectionRunState } from "../types.ts";
import { defaultCatalog } from "../catalog.ts";
import { duration, pct, usd } from "../format.ts";

/** Escape a table cell: pipes and newlines would break the row. */
const cell = (v: unknown): string => String(v).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

function table(header: string[], rows: unknown[][]): string[] {
  const out = [`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`];
  for (const r of rows) out.push(`| ${r.map(cell).join(" | ")} |`);
  return out;
}

const modelName = (id: string): string => {
  try {
    return defaultCatalog.get(id).name;
  } catch {
    return id;
  }
};
const cfg = (c: Config): string => `${modelName(c.model)} (${c.effort})`;

export function renderPlanMarkdown(plan: RoutedPlan): string {
  const { metrics: m, routes, decomposition: dec } = plan;
  const L: string[] = [];
  L.push(`# ${dec.title}`, "");
  const q = m.quality;
  L.push(
    `Routing this plan is expected to cost ${usd(m.cost.expected_with_cache)} against ${usd(m.baselines[0]?.cost ?? m.cost.expected_with_cache + m.savings.usd)} for the reference baseline (${m.savings.vs}), a saving of ${usd(m.savings.usd)} (${m.savings.pct.toFixed(1)}%); in 90% of simulated runs it costs at most ${usd(m.cost.p90)}. ` +
      `Mean final success probability is ${pct(q.mean_p_final)} (minimum ${pct(q.min_p_final)}), with ${q.below_floor.length} of ${m.subsections} subsections below their quality floor. ` +
      `The critical path takes about ${duration(m.schedule.critical_path_s)}.`,
    "",
  );
  if (m.single_config?.recommended) L.push(`> **Recommendation:** ${m.single_config.reason}`, "");

  L.push("## Assignments", "");
  L.push(
    ...table(
      ["ID", "Subsection", "Model", "Effort", "Difficulty", "First pass", "Final", "Verification", "Expected", "Baseline"],
      routes.map((r) => [
        r.id,
        r.title,
        r.model_name,
        r.effort,
        r.difficulty.level.toFixed(1),
        pct(r.p_first),
        pct(r.p_final),
        r.verification.method,
        usd(r.cost.expected),
        usd(r.cost.baseline),
      ]),
    ),
    "",
  );

  L.push("## Why each model", "");
  for (const r of routes) {
    L.push(`### ${r.id} - ${r.title}`, "");
    for (const reason of r.reasons) L.push(`- ${reason}`);
    L.push("");
    L.push(`Escalation ladder: ${r.escalation.length ? r.escalation.map(cfg).join(" -> ") : "none"}`, "");
    if (r.flags.length) L.push(`Flags: ${r.flags.join(", ")}`, "");
  }

  L.push("## Schedule", "");
  m.schedule.waves.forEach((w, i) => L.push(`${i + 1}. Wave ${i + 1}: ${w.join(", ")}${w.length > 1 ? " (parallel)" : ""}`));
  L.push("", `Critical path: ${m.schedule.critical_path.join(" -> ")} (${duration(m.schedule.critical_path_s)}).`, "");

  L.push("## Costs and baselines", "");
  L.push(
    ...table(
      ["Plan", "Cost", "Below floor", "Mean first pass"],
      [
        ["Routed plan (expected)", usd(m.cost.expected_with_cache), q.below_floor.length, pct(routes.reduce((s, r) => s + r.p_first, 0) / (routes.length || 1))],
        ...m.baselines.map((b) => [b.label, usd(b.cost), b.below_floor, pct(b.mean_p_first)]),
      ],
    ),
    "",
  );
  L.push(`- Prompt-cache saving: ${usd(m.cost.cache_saving)}`);
  L.push(`- Batch saving available: ${usd(m.cost.batch_saving_available)}`);
  L.push(`- Planner overhead: ${usd(m.planner_overhead)}`, "");

  L.push("## Model mix", "");
  L.push(
    ...table(
      ["Model", "Subsections", "Repetitions", "Expected cost", "Share of cost"],
      m.model_mix.map((e) => [e.model_name, e.subsections, e.repetitions, usd(e.expected_cost), pct(e.share_of_cost)]),
    ),
    "",
  );

  if (plan.issues.length) {
    L.push("## Issues", "");
    for (const level of ["error", "warning", "info"] as const) {
      const xs: Issue[] = plan.issues.filter((i) => i.level === level);
      if (!xs.length) continue;
      L.push(`### ${level[0]!.toUpperCase()}${level.slice(1)}`, "");
      for (const i of xs) L.push(`- ${i.subsection ? `**${i.subsection}**: ` : ""}${i.message} (\`${i.code}\`)`);
      L.push("");
    }
  }
  if (dec.open_questions.length) {
    L.push("## Open questions", "");
    for (const x of dec.open_questions) L.push(`- ${x}`);
    L.push("");
  }
  if (dec.assumptions.length) {
    L.push("## Assumptions", "");
    for (const x of dec.assumptions) L.push(`- ${x}`);
    L.push("");
  }
  L.push(`Generated by model-optimizer · prices as of ${m.pricing_as_of} · capability ceilings are priors calibrated by \`mopt stats\``, "");
  return L.join("\n");
}

function plannedRoute(plan: RoutedPlan, id: string): Routing | undefined {
  return plan.routes.find((r) => r.id === id);
}

export function renderRunMarkdown(summary: RunSummary, plan: RoutedPlan): string {
  const t = summary.totals;
  const L: string[] = [];
  L.push(`# Run report: ${summary.plan_title}`, "");
  const savedUsd = t.baseline_usd - t.spent_usd;
  const savedPct = t.baseline_usd > 0 ? (savedUsd / t.baseline_usd) * 100 : 0;
  const attempted = t.done + t.failed;
  L.push(`- Status: **${summary.status}** (${summary.started_at} to ${summary.ended_at}, ${duration(t.elapsed_s)})`);
  L.push(`- Spent ${usd(t.spent_usd)} vs estimate ${usd(t.est_total_usd)} vs baseline ${usd(t.baseline_usd)}`);
  L.push(`- Savings vs baseline: ${usd(savedUsd)} (${savedPct.toFixed(1)}%)`);
  L.push(`- First-pass success: ${t.first_pass_successes} of ${attempted} (${attempted ? pct(t.first_pass_successes / attempted) : "n/a"})`);
  L.push(`- Escalations: ${t.escalations}`);
  L.push(`- Subsections: ${t.done} done, ${t.failed} failed, ${t.skipped} skipped, ${t.pending} pending`, "");

  L.push("## Subsections", "");
  L.push(
    ...table(
      ["ID", "Title", "Planned model", "Final model", "Attempts", "Estimated", "Actual", "Delta", "Status"],
      summary.states.map((s) => {
        const r = plannedRoute(plan, s.id);
        const d = s.cost_usd - s.est_cost_usd;
        return [
          s.id,
          s.title,
          r ? `${r.model_name} (${r.effort})` : "-",
          s.final_model ? modelName(s.final_model) : "-",
          s.attempts.length,
          usd(s.est_cost_usd),
          usd(s.cost_usd),
          `${d >= 0 ? "+" : ""}${usd(d)}`,
          s.status,
        ];
      }),
    ),
    "",
  );

  const noteworthy = summary.states.filter((s: SubsectionRunState) => s.attempts.length > 1 || s.status === "failed");
  if (noteworthy.length) {
    L.push("## Escalations and failures", "");
    for (const s of noteworthy) {
      L.push(`### ${s.id} - ${s.title}`, "");
      for (const a of s.attempts) {
        const v = a.verdict;
        L.push(`- Attempt ${a.attempt}: ${modelName(a.model)} (${a.effort}), ${a.status}, ${usd(a.cost_usd)}${v ? `, score ${pct(v.score)}` : ""}`);
        if (a.error) L.push(`  - Error: ${a.error}`);
        if (v?.failed_criteria.length) for (const c of v.failed_criteria) L.push(`  - Failed criterion: ${c}`);
        if (v?.feedback) L.push(`  - Feedback: ${v.feedback}`);
      }
      L.push("");
    }
  }
  L.push("## Output", "", `Artifacts and outputs are in \`${summary.out_dir}\`.`, "");
  return L.join("\n");
}
