// Single-file builds for offline sharing.
// Inlines every stylesheet, script and icon referenced by each suite page into ONE .html file
// that works when opened straight from disk — so it can be passed phone-to-phone by
// WhatsApp, Bluetooth, USB or SD card in places without reliable internet.
//
// Usage: node tools/bundle.cjs            -> writes dist/<name>.html for each suite
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'dist');
const SUITES = [
  { dir: 'student', out: 'medical-student-studio.html' },
  { dir: 'clinician', out: 'clinician-toolkit.html' },
  { dir: 'health', out: 'salus.html' }
];

function safeScript(js) {
  // Prevent the HTML parser from ending or mis-parsing the inline script.
  return js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
}
function dataUri(file) {
  const ext = path.extname(file).toLowerCase();
  const mime = { '.svg': 'image/svg+xml', '.png': 'image/png' }[ext] || 'application/octet-stream';
  return `data:${mime};base64,${fs.readFileSync(file).toString('base64')}`;
}

function bundle(suite) {
  const pageDir = path.join(ROOT, suite.dir);
  let html = fs.readFileSync(path.join(pageDir, 'index.html'), 'utf8');
  const missing = [];
  // Stylesheets
  html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) => {
    const f = path.resolve(pageDir, href);
    if (!fs.existsSync(f)) { missing.push(href); return ''; }
    return `<style>\n${fs.readFileSync(f, 'utf8')}\n</style>`;
  });
  // Scripts (classic, in order). Missing files are dropped (and reported).
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
    const f = path.resolve(pageDir, src);
    if (!fs.existsSync(f)) { missing.push(src); return `<!-- missing: ${src} -->`; }
    return `<script>/* ${src} */\n${safeScript(fs.readFileSync(f, 'utf8'))}\n</script>`;
  });
  // Icons: inline the SVG favicon; drop the manifest and touch icon (not meaningful from file://).
  html = html.replace(/<link rel="icon" href="([^"]+)" type="image\/svg\+xml">/, (m, href) => {
    const f = path.resolve(pageDir, href);
    return fs.existsSync(f) ? `<link rel="icon" href="${dataUri(f)}" type="image/svg+xml">` : '';
  });
  html = html.replace(/\s*<meta http-equiv="Content-Security-Policy"[^>]*>/, ''); // inline build needs inline scripts
  html = html.replace(/\s*<link rel="manifest"[^>]*>/, '').replace(/\s*<link rel="apple-touch-icon"[^>]*>/, '');
  html = html.replace('<head>', `<head>\n  <!-- Single-file offline build of ${suite.dir}/ generated by tools/bundle.cjs on ${new Date().toISOString().slice(0, 10)}. Open it in any modern browser; no internet needed. -->`);
  fs.mkdirSync(OUT, { recursive: true });
  const outFile = path.join(OUT, suite.out);
  fs.writeFileSync(outFile, html);
  return { file: path.relative(ROOT, outFile), kb: Math.round(fs.statSync(outFile).size / 1024), missing };
}

const results = SUITES.map(bundle);
for (const r of results) {
  console.log(`${r.file}  ${r.kb} KB${r.missing.length ? `  (skipped missing: ${r.missing.join(', ')})` : ''}`);
}
